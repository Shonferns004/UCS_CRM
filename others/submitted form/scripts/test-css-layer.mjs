// Cross-check the design layer against the markup: every class the JSX uses
// must have a rule, and every rule must be used. Catches both halves of drift
// -- a class with no styling renders unstyled, and a rule with no markup is
// dead weight that misleads the next person editing the sheet.
//   Run alone: node scripts/test-css-layer.mjs
import { readFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, '..', 'src')
const componentsDir = join(src, 'components')

// Every component is checked, so a new file cannot quietly ship unstyled.
const jsxFiles = readdirSync(componentsDir).filter(f => f.endsWith('.jsx'))
const jsx = jsxFiles.map(f => readFileSync(join(componentsDir, f), 'utf8')).join('\n')
const css = readFileSync(join(src, 'index.css'), 'utf8')

// Tailwind utilities are used deliberately in the markup and are generated by
// the @theme remap, not by this layer.
const UTILITIES = new Set([
  'hidden', 'animate-spin', 'opacity-25', 'opacity-75', 'mt-3', 'mt-6', 'w-4', 'h-4', 'w-10', 'h-10',
])

// Built at runtime via a template, so a literal scan of the markup cannot see
// them. Declaring them here is what keeps this check honest.
const DYNAMIC = new Set(['toast-success', 'toast-error'])

const used = new Set()
// `className="..."` attributes, `className={`...`}` templates, and plain
// `el.className = '...'` assignments (the toast is built that way).
const CLASS_SOURCES = [
  /className=(?:"([^"]*)"|'([^']*)'|\{`([^`]*)`\})/g,
  /\.className\s*=\s*(?:"([^"]*)"|'([^']*)'|`([^`]*)`)/g,
]
for (const re of CLASS_SOURCES) {
  for (const m of jsx.matchAll(re)) {
    const raw = m[1] ?? m[2] ?? m[3] ?? ''
    for (const c of raw.split(/\s+/)) {
      const name = c.trim()
      if (name && !name.includes('$') && !name.includes('{')) used.add(name)
    }
  }
}

const defined = new Set()
// Strip comments first: the layer cites HR class names (`.panel-hr .field`,
// `.hrf-section-title`) in prose, and those are references, not rules.
// Then strip every url() body -- the data-URI chevron holds an inline SVG and
// the @font-face blocks point at .woff2 files, and a filename like
// `/fonts/poppins-latin-400.woff2` would otherwise read as a class named
// "woff2".
const cssBody = css
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/url\((?:"[^"]*"|'[^']*'|[^)]*)\)/g, 'url()')
for (const m of cssBody.matchAll(/\.([a-zA-Z][\w-]*)/g)) defined.add(m[1])

const missing = [...used].filter(c => !defined.has(c) && !UTILITIES.has(c)).sort()
const dead = [...defined].filter(c => !used.has(c) && !DYNAMIC.has(c)).sort()

// The PWA chrome colour is declared in three places with no shared source: the
// --sage token here, the <meta name="theme-color"> in index.html, and the
// manifest in vite.config.js. Drift is invisible in review but obvious on a
// phone, so it is asserted rather than remembered.
const token = (name) => {
  const m = css.match(new RegExp(name + ':\\s*(#[0-9A-Fa-f]{3,8})'))
  return m ? m[1].toUpperCase() : null
}
const grab = (src, re) => {
  const m = src.match(re)
  return m ? m[1].toUpperCase() : null
}
const html = readFileSync(join(here, '..', 'index.html'), 'utf8')
const vite = readFileSync(join(here, '..', 'vite.config.js'), 'utf8')
const sage = token('--sage')
const sand = token('--sand')

const theme = []
const same = (name, actual, expected) => {
  if (actual !== expected) theme.push(`${name}: got ${actual}, expected ${expected}`)
}
same('index.html theme-color vs --sage', grab(html, /name="theme-color"\s+content="(#[0-9A-Fa-f]+)"/), sage)
same('manifest theme_color vs --sage', grab(vite, /theme_color:\s*'(#[0-9A-Fa-f]+)'/), sage)
same('manifest background_color vs --sand', grab(vite, /background_color:\s*'(#[0-9A-Fa-f]+)'/), sand)
if (!/body\{[^}]*background:var\(--sand\)/.test(cssBody)) {
  theme.push('body background is not --sand, so the splash screen will not match first paint')
}

console.log(`  css layer : ${used.size} classes used, ${defined.size} rules defined (${jsxFiles.length} component${jsxFiles.length === 1 ? '' : 's'})`)
if (missing.length) console.log('    USED BUT UNSTYLED:\n      ' + missing.join('\n      '))
if (dead.length) console.log('    DEFINED BUT UNUSED:\n      ' + dead.join('\n      '))
if (theme.length) console.log('    THEME DRIFT:\n      ' + theme.join('\n      '))
if (missing.length || dead.length || theme.length) process.exit(1)
