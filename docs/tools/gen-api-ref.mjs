// Generator for docs/06-API-Reference/*.md
// Reads backend/src/routes/*.js and backend/src/index.js prefix mapping.
// Usage: node docs/tools/gen-api-ref.mjs
import fs from "fs";
import path from "path";

const routesDir = "backend/src/routes";
const indexSrc = fs.readFileSync("backend/src/index.js", "utf8");

// ---- prefix mapping from index.js
const prefixMap = {};
const useRe = /app\.use\(\s*(['"`])([^'"`]+)\1\s*,\s*([A-Za-z_][A-Za-z0-9_]*Routes|metropadRouter|sevakLibraryRouter)\s*\)/g;
let m;
while ((m = useRe.exec(indexSrc)) !== null) {
  const file = m[3];
  if (!(file in prefixMap)) prefixMap[file] = m[2];
}
const fallback = {
  metropadRouter: "/api/metropad",
  sevakLibraryRouter: "/api/sevak-library",
};

// ---- module grouping of route files
const groups = {
  "01-Authentication": ["authRoutes", "codeRoutes", "configRoutes", "userRoutes", "userSettingsRoutes", "profileUpdateRequestRoutes"],
  "02-Workers-HR": ["workerRoutes", "workerBankImportRoutes", "leaveRoutes", "salaryRoutes", "loanRoutes", "letterRoutes", "holidayRoutes", "hrRoutes", "hrDailyReportRoutes", "quizRoutes"],
  "03-Attendance-QR": ["attendanceRoutes", "attendanceCorrectionRoutes", "qrRoutes", "biometricRoutes", "meetingRoutes"],
  "04-Recruitment": ["leadRoutes", "callLogRoutes", "recruiterRoutes", "onboardingRoutes"],
  "05-FRO-Incentives": ["froRoutes", "froWhatsAppRoutes", "incentiveRoutes", "specialIncentiveRoutes", "leadIncentiveRoutes", "causeRoutes"],
  "06-Accounts-Finance": ["accountsRoutes", "bankAuditRoutes", "bankStatementRoutes", "emailImportRoutes", "scraperRoutes", "webhookRoutes", "whatsappRoutes"],
  "07-Beneficiaries": ["beneficiaryRoutes", "beneficiaryImportRoutes", "programRoutes", "benefitRoutes", "distributionRoutes", "operatorRoutes", "reportRoutes", "ocrRoutes"],
  "08-Events": ["eventRoutes", "eventHeadRoutes", "importantDaysRoutes", "calendarRoutes"],
  "09-Communication": ["chatRoutes", "noticeRoutes", "notificationRoutes", "notificationAdminRoutes", "ticketRoutes", "hrWhatsAppRoutes", "reminderRoutes", "whatsappCrmRoutes", "whatsappCrmDataRoutes", "whatsappEnhancementsRoutes"],
  "10-Admin-Platform": ["ngoAdminRoutes", "superAdminRoutes", "ngoRoutes", "ngoAllocationRoutes", "taskRoutes", "taskAssignmentRoutes", "assetsRoutes", "settingsRoutes", "teamRoutes", "dataSourceRoutes", "dataImportRoutes", "s3BrowserRoutes", "envAdminRoutes", "tempCleanupRoutes", "simCardRoutes", "simInventoryRoutes", "votingRoutes", "audienceVotingRoutes", "achievementRoutes", "developerTicketRoutes", "certificateRoutes", "bulkAgentImportRoutes", "agentTransferRoutes"],
  "11-Special-Apps": ["sevakLibraryRouter", "metropadRouter", "aadhaarRoutes"],
};

// ---- extraction
function extract(file) {
  const src = fs.readFileSync(path.join(routesDir, file), "utf8");
  const rows = [];
  const re = /router\.(get|post|put|patch|delete|all)\s*\(\s*(['"`])([^'"`]*)\2\s*[,)]([\s\S]*?)(?:\)\s*;|\n\)\s*;)/g;
  let mm;
  while ((mm = re.exec(src)) !== null) {
    const method = mm[1].toUpperCase();
    const p = mm[3];
    let args = mm[4] || "";
    args = args.split("\n").map((l) => l.trim()).filter(Boolean).join(" ");
    rows.push({ method, path: p, args: args.replace(/\s+/g, " ").slice(0, 140) });
  }
  return rows;
}

// ---- render
const outDir = "docs/06-API-Reference";
const indexLines = ["# UCS CRM — API Reference (Index)", "",
  "> Generated 2026-10-13 from `backend/src/routes/*.js` and mount prefixes in `backend/src/index.js`.", "",
  "> Status: **Verified** (routes read from source). Auth/controller column reproduces route-file text verbatim; some rows truncated.",
  "> Endpoint paths shown are full paths = mount prefix + route path. Relative route paths are available inside each group file.", "",
  "Route extraction covers `router.METHOD(...)` calls. Inline handlers, cron endpoints and non-router mounts in `index.js` are documented in `../12-Troubleshooting/` and panel docs.", "",
  "## Group index", "",
  "| Module group | File | Route files |",
  "| --- | --- | --- |"];

for (const [g, files] of Object.entries(groups)) {
  const lines = [`# API — ${g.replace(/^\d+-/, "")}`, "",
    `> Generated by ${"docs/tools/gen-api-ref.mjs"} from route files. Status: Verified (routes read from source); auth strings verbatim.`, "",
  ];
  let count = 0;
  for (const f of files) {
    if (!fs.existsSync(path.join(routesDir, f + ".js"))) continue;
    const rows = extract(f + ".js");
    if (!rows.length) continue;
    const prefix = prefixMap[f] || fallback[f] || "";
    count += rows.length;
    lines.push(`## ${f}.js`, "");
    if (prefix) lines.push(`**Mount prefix:** \`${prefix}\``, "");
    lines.push("| Method | Path | Auth / controller (as written) |", "| --- | --- | --- |");
    for (const r of rows) lines.push(`| ${r.method} | \`${prefix}${r.path}\` | \`${r.args}\` |`);
    lines.push("");
  }
  const outFile = path.join(outDir, `API-${g}.md`);
  lines.unshift(`# API Reference — ${g.replace(/^\d+-/, "")}`, "", `> ${count} endpoints · mount prefixes from backend/src/index.js · auth strings verbatim (may be truncated).`, "");
  fs.writeFileSync(outFile, lines.join("\n"), "utf8");
  console.log(`wrote ${outFile} (${count} endpoints)`);
  indexLines.push(`| ${g.replace(/^\d+-/, "")} | \`API-${g}.md\` | \`${files.join("`, `")}\` |`);
}

fs.writeFileSync(path.join(outDir, "README.md"), indexLines.join("\n") + "\n", "utf8");
console.log("done");